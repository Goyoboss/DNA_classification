from sklearn.model_selection import train_test_split
import pandas as pd

# 1. Cargar el dataset completo que unimos antes (o usar df_completo directamente si lo tienes en memoria)
df = pd.read_csv('dataset_completo.csv')

# 2. Definir tu columna objetivo (Target)
# Reemplaza 'GeneType' por el nombre exacto de la columna que tu modelo debe clasificar
columna_objetivo = 'GeneType'

# Separar Features (X) y Target (y)
# X contendrá las secuencias de ADN y otras variables predictoras
# y contendrá la etiqueta o clase biológica
X = df.drop(columns=[columna_objetivo])
y = df[columna_objetivo]

# 3. Separar en Entrenamiento (Train) y Prueba (Test)
# test_size=0.2 significa que el 20% irá a test y el 80% a entrenamiento
# stratify=y asegura que las clases de ADN se mantengan bien proporcionadas en ambos grupos
X_train, X_test, y_train, y_test = train_test_split(
    X, y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

print("¡Datos separados correctamente para modelar!")
print(f"X_train shape: {X_train.shape}, y_train shape: {y_train.shape}")
print(f"X_test shape: {X_test.shape}, y_test shape: {y_test.shape}")

# Opcional: Si quieres guardarlos en archivos independientes listos para tu fase de entrenamiento:
train_final = X_train.copy()
train_final[columna_objetivo] = y_train

test_final = X_test.copy()
test_final[columna_objetivo] = y_test

train_final.to_csv('train_final.csv', index=False)
test_final.to_csv('test_final.csv', index=False)
print("Archivos 'train_final.csv' y 'test_final.csv' exportados con éxito.")